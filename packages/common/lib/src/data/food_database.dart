  /// Returns all items whose name or category contains [query] (case-insensitive).
  static List<FoodItem> search(String query) {
    final lower = query.toLowerCase();
    return items
        .where((item) =>
            item.name.toLowerCase().contains(lower) ||
            item.category.toLowerCase().contains(lower))
        .toList();
  }

  /// Returns the item with [id], or null if not found.
  static FoodItem? findById(String id) {
    try {
      return items.firstWhere((item) => item.id == id);
    } catch (_) {
      return null;
    }
  }
